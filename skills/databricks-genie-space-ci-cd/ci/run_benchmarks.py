#!/usr/bin/env python3
"""
run_benchmarks.py — L2b BEHAVIORAL REGRESSION (nightly, after the L2 audit).

Catches "right definition, wrong answer": a space passes L1+L2 (definition in
sync with the repo) but now returns a wrong number because upstream data changed
or a metric is subtly mis-specified. Structural checks can't see that; only
asking the question and grading the answer can.

TWO BACKENDS:
  --native  : use Databricks' built-in benchmark evaluation
              (genie_create_eval_run / genie_get_eval_run / genie_list_eval_results).
              Preferred when your benchmark questions are registered IN the space
              as benchmark questions — Databricks runs and grades them for you.
  (default) : the custom harness — asks each question via the conversation API
              and grades locally with scalar/rowset/sql modes. Use when you want
              SQL-fragment assertions (did it route through the certified metric
              view?) or golden values stored in the repo rather than in the space.

DETERMINISM RULE (the #1 footgun): every question/golden must be date-pinned.
The harness substitutes a pinned as_of_date and REFUSES any question containing
CURRENT_DATE/NOW()/etc unless allow_nondeterministic: true. An unpinned benchmark
reports a fake regression every night and trains people to ignore alerts.

GRADING MODES (custom backend):
  scalar : single number, relative tolerance (default 0.5%).
  rowset : unordered set of rows, exact.
  sql    : assert an expected fragment (e.g. the certified metric view's FQN)
           appears in Genie's generated SQL. Most robust — survives data changes,
           fails if the space stops routing through the governed definition.

BENCHMARK FILE: benchmarks/<space>.bench.yaml  (see benchmarks/treasury.bench.yaml).

Exit codes: 0 pass | 2 setup/config | 5 real failures (regression/error/bad
config) | 6 ONLY non-deterministic benchmarks were blocked (authoring fix).
"""

from __future__ import annotations

import argparse
import re
import sys
import time

import yaml

import databricks_helpers as h
from _core import ConfigError, get_logger

log = get_logger("drift.L2b")

NONDETERMINISTIC = re.compile(
    r"\b(current_date|current_timestamp|now\s*\(|getdate\s*\(|today\s*\()", re.I)

# Genie conversation API free tier ~5 q/min/workspace. >>> ADAPT if higher.
SECONDS_BETWEEN_QUESTIONS = 13


# ------------------------------------------------------------------------------
# Grading (pure functions — fully unit-tested)
# ------------------------------------------------------------------------------
def grade_scalar(golden, rows, tolerance) -> tuple[bool, str]:
    try:
        actual = float(rows[0][0])
    except (IndexError, TypeError, ValueError):
        return False, f"expected a scalar, got rows={rows!r}"
    g = float(golden)
    ok = abs(actual) < 1e-9 if g == 0 else abs(actual - g) / abs(g) <= tolerance
    return ok, f"golden={g}, actual={actual}, tol={tolerance}"


def grade_rowset(golden, rows) -> tuple[bool, str]:
    def norm(r):
        return tuple(sorted(tuple(str(c) for c in row) for row in r))
    return norm(golden) == norm(rows), \
        f"golden_rows={len(golden)}, actual_rows={len(rows)}"


def grade_sql(expected_sql, generated_sql) -> tuple[bool, str]:
    if generated_sql is None:
        return False, "no SQL was generated by Genie"

    def canon(s: str) -> str:
        return re.sub(r"\s+", " ", s.lower()).replace("`", "").strip().rstrip(";")
    frag, gen = canon(expected_sql), canon(generated_sql)
    return frag in gen, f"expected_fragment={frag!r} present={frag in gen}"


def is_nondeterministic(text: str) -> bool:
    return bool(NONDETERMINISTIC.search(text or ""))


# ------------------------------------------------------------------------------
# Custom backend: ask + grade locally
# ------------------------------------------------------------------------------
def run_space_custom(space_name, space_id, cfg, adapter,
                     sleep=SECONDS_BETWEEN_QUESTIONS) -> list[tuple[str, str]]:
    """Return (category, message) failures. category in
    {blocked, regression, error, config}."""
    bf = h.BENCHMARKS_DIR / f"{space_name}{h.BENCH_SUFFIX}"
    if not bf.exists():
        log.warning("  no benchmark file at %s — skipping.", bf)
        return []
    spec = yaml.safe_load(bf.read_text()) or {}
    as_of = str(spec.get("as_of_date", "")).strip()
    if not as_of:
        return [("config", f"{space_name}: benchmark file has no 'as_of_date'. "
                 f"Pin a date for deterministic runs.")]

    failures: list[tuple[str, str]] = []
    for q in spec.get("questions", []):
        qid = q.get("id", "?")
        try:
            question = q["question"].format(as_of_date=as_of)
        except KeyError as e:
            failures.append(("config", f"{space_name}/{qid}: bad placeholder {e}"))
            continue
        allow_nd = bool(q.get("allow_nondeterministic", False))
        if is_nondeterministic(question + " " + str(q.get("expected_sql", ""))) and not allow_nd:
            failures.append(("blocked", f"{space_name}/{qid}: non-deterministic "
                             f"token (CURRENT_DATE/NOW/etc). Pin the date or set "
                             f"allow_nondeterministic: true."))
            log.error("  %s: BLOCKED (non-deterministic)", qid)
            continue

        log.info("  %s: asking \"%s...\"", qid, question[:60])
        try:
            gen_sql, rows = adapter.ask(space_id, question)
        except Exception as e:  # adapter already typed/retried
            failures.append(("error", f"{space_name}/{qid}: API error: {e}"))
            log.error("  %s: API error %s", qid, e)
            continue

        match = q.get("match", "scalar")
        if match == "scalar":
            ok, detail = grade_scalar(q["golden"], rows, q.get("tolerance", 0.005))
        elif match == "rowset":
            ok, detail = grade_rowset(q["golden"], rows)
        elif match == "sql":
            ok, detail = grade_sql(q["expected_sql"], gen_sql)
        else:
            ok, detail = False, f"unknown match mode '{match}'"

        if ok:
            log.info("  %s: pass (%s)", qid, detail)
        else:
            failures.append(("regression", f"{space_name}/{qid}: REGRESSION — "
                             f"{detail}\n      generated SQL: {gen_sql}"))
            log.error("  %s: FAIL (%s)", qid, detail)
        if sleep:
            time.sleep(sleep)
    return failures


# ------------------------------------------------------------------------------
# Native backend: Databricks runs + grades the space's registered benchmarks
# ------------------------------------------------------------------------------
def run_space_native(space_name, space_id, adapter) -> list[tuple[str, str]]:
    """Use genie_create_eval_run + poll + list results. Returns (category, msg)
    failures. Requires benchmark questions registered in the space.
    >>> ADAPT: result field names (passed/score/status) per your SDK version;
    we read defensively."""
    genie = adapter.client.genie
    try:
        run = adapter._wrap_sdk_call(genie.genie_create_eval_run, space_id=space_id)
    except Exception as e:
        return [("error", f"{space_name}: could not start native eval run: {e}")]
    run_id = getattr(run, "eval_run_id", None) or getattr(run, "id", None)
    if not run_id:
        return [("error", f"{space_name}: native eval run returned no id")]

    # Poll for completion.
    import time as _t
    deadline = _t.time() + 1200  # 20 min
    status = None
    while _t.time() < deadline:
        cur = adapter._wrap_sdk_call(genie.genie_get_eval_run,
                                     space_id=space_id, eval_run_id=run_id)
        status = getattr(getattr(cur, "status", None), "value",
                         getattr(cur, "status", None))
        if str(status).upper() in ("COMPLETED", "FINISHED", "SUCCEEDED", "FAILED"):
            break
        _t.sleep(10)

    results = adapter._wrap_sdk_call(genie.genie_list_eval_results,
                                     space_id=space_id, eval_run_id=run_id)
    items = getattr(results, "results", None) or getattr(results, "eval_results", []) or []
    failures = []
    for r in items:
        passed = getattr(r, "passed", None)
        if passed is None:
            score = getattr(r, "score", None)
            passed = (score is not None and float(score) >= 1.0)
        qid = getattr(r, "benchmark_question_id", None) or getattr(r, "id", "?")
        if not passed:
            failures.append(("regression",
                             f"{space_name}/{qid}: native eval failed "
                             f"(score/pass={getattr(r,'score',passed)})"))
            log.error("  native %s: FAIL", qid)
        else:
            log.info("  native %s: pass", qid)
    return failures


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="L2b benchmark regression")
    ap.add_argument("--env", default="prod")
    ap.add_argument("--only", default=None)
    ap.add_argument("--native", action="store_true",
                    help="use Databricks' built-in eval runs instead of the "
                         "local harness")
    ap.add_argument("--open-workitem", action="store_true")
    args = ap.parse_args(argv)

    cfg = h.load_config()
    adapter = h.DatabricksAdapter(cfg["workspace"]["host"])
    log.info("L2b benchmark regression — env=%s backend=%s",
             args.env, "native" if args.native else "custom")

    all_failures: list[tuple[str, str]] = []
    for name, spec in (cfg.get("genie_spaces") or {}).items():
        if args.only and name != args.only:
            continue
        try:
            space_id = h.get_space_id(cfg, name, args.env)
        except ConfigError as e:
            log.warning("skip '%s': %s", name, e)
            continue
        log.info("Space '%s':", name)
        if args.native:
            all_failures += run_space_native(name, space_id, adapter)
        else:
            all_failures += run_space_custom(name, space_id, cfg, adapter)

    if not all_failures:
        log.info("L2b PASSED — all benchmark answers match golden results.")
        return 0

    print("\n" + "=" * 70)
    log.error("L2b found %d problem(s):", len(all_failures))
    for i, (cat, msg) in enumerate(all_failures, 1):
        print(f"[{i}] ({cat}) {msg}\n")

    if args.open_workitem:
        try:
            from audit_drift import open_azure_workitem
            open_azure_workitem(
                f"[Genie benchmark] {len(all_failures)} issue(s) ({args.env})",
                "Nightly L2b found problems:\n\n"
                + "\n".join(f"({c}) {m}" for c, m in all_failures))
        except Exception as e:
            log.error("could not open work item: %s", e)

    print("=" * 70)
    print("A regression means a space's ANSWER changed even if its definition "
          "didn't. A human decides: update the golden (new answer is correct) or "
          "fix the space (it's broken).")
    categories = {cat for cat, _ in all_failures}
    return 6 if categories <= {"blocked"} else 5


def _entry() -> int:
    try:
        return main()
    except ConfigError as e:
        log.error("setup/config error: %s", e)
        return 2
    except Exception as e:
        log.error("unexpected error: %s", e)
        return 2


if __name__ == "__main__":
    sys.exit(_entry())
